def test_vesclass_array_stacking_preserves_rgb_units_and_binary_support():
    rgb = np.full((7, 9, 3), [4096, 1024, 80], dtype=np.uint16)
    vessel = np.zeros((7, 9), np.uint8)
    vessel[:, 4] = 255
    inputs = stack_vesclass_inputs(rgb, vessel)
    assert inputs.shape == (4, 7, 9) and inputs.dtype == np.float32
    np.testing.assert_array_equal(inputs[:3], rgb.transpose(2, 0, 1))
    np.testing.assert_array_equal(inputs[3], vessel > 0)
    assert inputs.flags.c_contiguous
    with pytest.raises(ValueError, match="Threshold vessel probabilities"):
        stack_vesclass_inputs(rgb, vessel.astype(np.float32) / 300)


def test_matlab_quantization_uses_positive_half_up_and4096_white():
    rgb = np.array([[[0.0, 1 / 8192, 1.0]]])
    np.testing.assert_array_equal(quantize_vesclass_rgb(rgb), [[[0, 1, 4096]]])
    assert quantize_vesclass_rgb(rgb).dtype == np.uint16
    rgb = np.array([[[0.0, 0.5 / 255, 1.0]]])
    np.testing.assert_array_equal(quantize_vesclass_rgb(rgb, "uint8"), [[[0, 1, 255]]])


def write_dicom(path, pixels):
    meta = FileMetaDataset()
    meta.TransferSyntaxUID = ExplicitVRLittleEndian
    meta.MediaStorageSOPClassUID = SecondaryCaptureImageStorage
    meta.MediaStorageSOPInstanceUID = generate_uid()
    dataset = FileDataset(path, {}, file_meta=meta, preamble=b"\0" * 128)
    dataset.SOPClassUID = meta.MediaStorageSOPClassUID
    dataset.SOPInstanceUID = meta.MediaStorageSOPInstanceUID
    dataset.Rows, dataset.Columns = pixels.shape
    dataset.SamplesPerPixel = 1
    dataset.PhotometricInterpretation = "MONOCHROME2"
    dataset.BitsAllocated = 16
    dataset.BitsStored = 16
    dataset.HighBit = 15
    dataset.PixelRepresentation = 0
    dataset.RescaleSlope = 3
    dataset.RescaleIntercept = -1234
    dataset.PixelData = np.asarray(pixels, dtype="<u2").tobytes()
    dataset.save_as(path, enforce_file_format=True)


def test_dicom_loader_reproduces_network_predict_without_rescale_or_threshold(tmp_path):
    arrays = [np.full((7, 9), v, np.uint16) for v in (4096, 1024, 80)]
    vessel = np.zeros((7, 9), np.uint16)
    vessel[:, 4] = 255
    arrays.append(vessel)
    paths = [tmp_path / f"{channel}.dcm" for channel in ["R", "G", "B", "ves"]]
    for path, array in zip(paths, arrays):
        write_dicom(path, array)
    inputs = load_vesclass_dicoms(paths)
    np.testing.assert_array_equal(inputs, np.stack(arrays).astype(np.float32))
    assert inputs[3].max() == 255  # Original stored values, not array-helper binarization.
    assert inputs.dtype == np.float32 and inputs.flags.c_contiguous
    with pytest.raises(ValueError, match="exactly four"):
        load_vesclass_dicoms(paths[:3])


def test_bad_fov_and_geometry_fail_clearly():
    image, fov = fixture_image()
    with pytest.raises(ValueError, match="empty FOV"):
        prepare_single_net(image, fov=np.zeros_like(fov))
    with pytest.raises(ValueError, match="does not match"):
        prepare_single_net(image, fov=np.ones((4, 5)))
    with pytest.raises(ValueError, match="Unknown dataset"):
        prepare_single_net(image, dataset="unknown", fov=fov)
    with pytest.raises(ValueError, match="finite and positive"):
        prepare_single_net(image, fov=fov, pixels_per_degree=0)


@pytest.mark.parametrize("normalized", [False, True])
def test_raw_av_proxy_preserves_full_frame_and_binary_vessel_geometry(normalized):
    image, fov = fixture_image()
    before = image.copy()
    vessel = np.zeros(fov.shape, np.uint8)
    vessel[30:70, 60:64] = 255
    result = prepare_vesclass_raw_proxy(
        image,
        vessel,
        fov=fov,
        pixels_per_degree=2,
        field_of_view_degrees=30,
        fov_diameter_pixels=110,
        normalized=normalized,
    )
    assert result.geometry.crop_position == (0, 95, 0, 127)
    assert result.geometry.rescale_factor == 60 / 110
    assert result.image.shape == (53, 70, 3)
    assert result.vessel.shape == result.fov.shape == (53, 70)
    assert result.vessel.dtype == result.fov.dtype == bool
    assert result.image.dtype == np.uint16
    assert (
        np.isfinite(result.image).all() and result.image.min() >= 0 and result.image.max() <= 4096
    )
    assert result.profile["matlab_parity_certified"] is False
    assert result.profile["diameter_source"] == "explicit original-frame diameter calibration"
    assert result.inputs().shape == (4, 53, 70)
    assert result.inputs().dtype == np.float32
    assert set(np.unique(result.inputs()[3])) == {0.0, 1.0}
    np.testing.assert_array_equal(result.geometry.prepare_mask(vessel > 0), result.vessel)
    restored = result.geometry.restore(np.ones(result.vessel.shape, dtype=np.uint8))
    assert restored.shape == (96, 128) and restored.all()  # Entire frame, no FOV crop paste.
    np.testing.assert_array_equal(image, before)
    if normalized:
        assert not result.image[~result.fov].any()


def test_raw_av_proxy_marks_heuristic_diameter_and_requires_discrete_vessels():
    image, fov = fixture_image()
    vessel = np.zeros_like(fov)
    vessel[45:50, 40:90] = True
    result = prepare_vesclass_raw_proxy(
        image,
        vessel,
        fov=fov,
        pixels_per_degree=2,
        field_of_view_degrees=30,
        normalized=False,
    )
    assert result.profile["fov_diameter_pixels"] == 105
    assert "heuristic" in result.profile["diameter_source"]
    with pytest.raises(ValueError, match="Threshold vessel probabilities"):
        prepare_vesclass_raw_proxy(image, vessel.astype(np.float32) * 0.9, fov=fov)
    with pytest.raises(ValueError, match="finite and positive"):
        prepare_vesclass_raw_proxy(image, vessel, fov=fov, fov_diameter_pixels=0)
