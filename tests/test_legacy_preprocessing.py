def fixture_image():
    yy, xx = np.indices((96, 128))
    image = np.stack(
        [(xx * 2 + yy) % 170 + 30, (yy + xx) % 160 + 40, (3 * yy + 2 * xx) % 140 + 35], axis=-1
    ).astype(np.uint8)
    fov = ((xx - 64) ** 2 / 52**2 + (yy - 48) ** 2 / 36**2) <= 1
    image[~fov] = 0
    return image, fov


def sha(array):
    return hashlib.sha256(np.ascontiguousarray(array).tobytes()).hexdigest()


@pytest.mark.parametrize(
    "normalized,rgb_hash,tensor_hash",
    [
        (
            False,
            "b3105bdcf384d777e9e6bdb8c09c321e930d92cf94286a3651b0ea3b8e65e5c1",
            "e92764d0e2d1a316afab979500c12126aff13a9a8f329554c0311368816879ee",
        ),
        (
            True,
            "402c8b988f2370a3ea407e670d714a7adc7da7a48d6f04198b08ac1570ee797e",
            "b78287aabc0f641d319b0a3c76e32fb28bd3b5da32ed8adafd299c1bd5b24459",
        ),
    ],
)
def test_original_source_numeric_golden(normalized, rgb_hash, tensor_hash):
    # Generated by executing ORIGINAL LoaderGeneric.preprocess and optional
    # ORIGINAL local_contrast_and_clahe at7a152c3, not by this port.
    # Full provenance/real-image comparisons: reports/legacy/preprocessing-reference.json.
    image, fov = fixture_image()
    result = prepare_single_net(
        image, fov=fov, pixels_per_degree=2, field_of_view_degrees=45, normalized=normalized
    )
    assert result.image.shape == (51, 74, 3)
    assert result.geometry.bbox == (12, 84, 12, 116)
    assert result.geometry.rescale_factor == 0.703125
    assert sha(result.image) == rgb_hash
    assert sha(result.fov) == "0e5e8fe6d3e30a64c81c7c4876245bbfd61203b82e05394856366f57c968aa58"
    assert sha(result.tensor().numpy()) == tensor_hash
    assert result.image.dtype == np.uint8 and result.fov.dtype == bool
    assert result.tensor().is_contiguous()


def test_scale_uses_original_dimension_and_inverse_pastes_inclusive_crop():
    image = np.arange(20 * 30 * 3).reshape(20, 30, 3).astype(np.uint8)
    fov = np.zeros((20, 30), bool)
    fov[2:18, 4:25] = True
    result = prepare_single_net(image, fov=fov, pixels_per_degree=1, field_of_view_degrees=30)
    assert result.geometry.rescale_factor == 1
    assert result.image.shape == (16, 21, 3)
    np.testing.assert_array_equal(result.image, image[2:18, 4:25])
    mask = np.zeros((20, 30), np.uint8)
    mask[7, 13] = 2
    prepared_mask = result.geometry.prepare_mask(mask)
    assert prepared_mask[5, 9] == 2
    np.testing.assert_array_equal(result.geometry.restore(prepared_mask), mask)
    channels = np.stack([np.full((16, 21), 0.25), np.full((16, 21), 0.75)]).astype(np.float32)
    restored = result.geometry.restore(channels, order=1)
    assert restored.shape == (2, 20, 30)
    assert restored[0, 2, 4] == 0.25 and restored[1, 17, 24] == 0.75
    assert not restored[:, :2].any() and not restored[:, :, 25:].any()
    hwc = result.geometry.restore(channels.transpose(1, 2, 0), order=1)
    np.testing.assert_array_equal(hwc.transpose(2, 0, 1), restored)


def test_automatic_fov_uses_largest_component_and_fills_holes():
    yy, xx = np.indices((140, 180))
    image = np.zeros((140, 180, 3), np.uint8)
    image[(yy - 70) ** 2 + (xx - 105) ** 2 < 50**2] = [120, 100, 90]
    image[67:73, 102:108] = 0
    image[4:10, 4:10] = 255
    fov = get_fov_auto(image)
    assert fov[70, 105] and fov[50, 105]
    assert not fov[5, 5] and not fov[0].any()


